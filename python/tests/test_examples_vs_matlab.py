"""Integration tests comparing Python examples against MATLAB reference output.

Each test loads the MATLAB reference HDF5 (generated by generate_all_references.m),
runs the matching Python example, pairs the pixels by position (MATLAB and Python
order them differently) and compares the beamformed data pixel by pixel.
"""

import os

import h5py
import numpy as np
import pytest

from examples import (
    cpwc_linear,
    picmus_experiment_contrast,
    picmus_experiment_resolution,
    picmus_simulation_contrast,
    picmus_simulation_resolution,
)
from tests.matlab_compare import assert_pixelwise_match, match_pixels

REF_DIR = os.path.dirname(__file__)
DATA_DIR = os.path.join(os.path.dirname(__file__), "..", "..", "data")


# Pixelwise agreement required for every example
MIN_ENVELOPE_CORR = 0.999
MAX_RELATIVE_ERROR = 1e-2


def assert_matches_matlab(ref_file, b_data, name):
    """Compare Python beamformed data with the MATLAB reference, pixel by pixel."""
    with h5py.File(ref_file, "r") as f:
        ml_bf = (f["bf_real"][:] + 1j * f["bf_imag"][:]).T  # -> [pixel, ch, wave, frame]
        ml_x, ml_z = f["scan_x"][:], f["scan_z"][:]
    perm = match_pixels((ml_x, ml_z), (b_data.scan.x, b_data.scan.z))
    assert_pixelwise_match(
        ml_bf[perm], b_data.data, name, min_corr=MIN_ENVELOPE_CORR, max_rel_err=MAX_RELATIVE_ERROR
    )


class TestCPWCLinear:
    REF = os.path.join(REF_DIR, "ref_cpwc_linear.h5")
    DATA = os.path.join(DATA_DIR, "L7_CPWC_193328.uff")

    @pytest.fixture(scope="class")
    def result(self):
        if not os.path.exists(self.DATA):
            pytest.skip("Dataset not available")
        return cpwc_linear.main()

    @pytest.mark.skipif(not os.path.exists(REF), reason="Reference not available")
    def test_should_match_matlab_per_pixel(self, result):
        assert_matches_matlab(self.REF, result, "CPWC Linear")

    def test_should_produce_nonzero_output(self, result):
        assert np.abs(result.data).max() > 0

    def test_should_have_correct_pixel_count(self, result):
        assert result.data.shape[0] == 256 * 256


